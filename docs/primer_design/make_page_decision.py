NUMRE = re.compile(r"^[\d.%/ –→+-]+$")
def cell(v): return '<td class="' + ("n" if NUMRE.match(str(v)) else "") + '">' + html.escape(str(v)) + "</td>"
def tbl(rows, heads): return '<div class="tbl"><table><thead><tr>' + "".join(f"<th>{c}</th>" for c in heads) + "</tr></thead><tbody>" + "".join("<tr>" + "".join(cell(v) for v in r) + "</tr>" for r in rows) + "</tbody></table></div>"
